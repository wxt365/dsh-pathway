    await page.locator('.pw-reply-select').selectOption('reply-final');
    assert.equal(await page.locator('.pw-evidence-shared').count(),2);
    assert.equal(await page.locator('.pw-evidence-shared').first().textContent(),'共享 · 2 条结论');
    await page.locator('.pw-plan-card[data-kind=evidence]').filter({has:page.locator('.pw-evidence-shared')}).first().locator('.pw-plan-node-select').click();
    assert.match(await page.locator('.pw-detail').innerText(),/不是重复登记/);
    await page.keyboard.press('Escape');
    await page.locator('[data-plan-mode=execution]').click();
